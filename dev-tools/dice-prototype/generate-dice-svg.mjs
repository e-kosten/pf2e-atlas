function vertices(geometry) {
  const p = geometry.getAttribute('position');
  const unique = new Map();
  for (let i=0;i<p.count;i++) {
    const v = new Vector3().fromBufferAttribute(p,i);
    unique.set(v.toArray().map(x=>x.toFixed(5)).join(','),v);
  }
  return [...unique.values()];
}
// Supporting planes merge coplanar triangles into true polygonal faces.
function faces(points) {
  const planes = new Map();
  for(let a=0;a<points.length;a++) for(let b=a+1;b<points.length;b++) for(let c=b+1;c<points.length;c++) {
    const n = points[b].clone().sub(points[a]).cross(points[c].clone().sub(points[a]));
    if(n.length()<1e-6) continue;
    n.normalize();
    let d=n.dot(points[a]);
    const distances=points.map(p=>n.dot(p)-d);
    if(distances.some(x=>x>1e-5) && distances.some(x=>x< -1e-5)) continue;
    if(d<0){n.negate();d=-d;}
    const indices=points.flatMap((p,i)=>Math.abs(n.dot(p)-d)<1e-5?[i]:[]);
    const key=indices.join(',');
    if(planes.has(key))continue;
    const center=indices.reduce((v,i)=>v.add(points[i]),new Vector3()).divideScalar(indices.length);
    const u=points[indices[0]].clone().sub(center).normalize(), v=n.clone().cross(u);
    indices.sort((a,b)=>Math.atan2(points[a].clone().sub(center).dot(v),points[a].clone().sub(center).dot(u))-Math.atan2(points[b].clone().sub(center).dot(v),points[b].clone().sub(center).dot(u)));
    planes.set(key,{indices,normal:n,center});
  }
  return [...planes.values()];
}
const h=1.15, a=h*(1-Math.cos(Math.PI/5))/(1+Math.cos(Math.PI/5));
const d10=[new Vector3(0,0,h),new Vector3(0,0,-h),...Array.from({length:10},(_,i)=>new Vector3(Math.cos(i*Math.PI/5),Math.sin(i*Math.PI/5),i%2?a:-a))];
const models={4:vertices(new TetrahedronGeometry()),6:vertices(new BoxGeometry()),8:vertices(new OctahedronGeometry()),10:d10,12:vertices(new DodecahedronGeometry()),20:vertices(new IcosahedronGeometry())};
const output={};
const round=n=>Number(n.toFixed(3));
for(const [sides,points] of Object.entries(models)){
  const polygons=faces(points);
  assert.equal(polygons.length,Number(sides));
  const front=polygons[0];
  const faceOn=new Quaternion().setFromUnitVectors(front.normal,new Vector3(0,0,1));
  const tip = sides === '10'
    ? front.indices.reduce((best,i)=>points[i].distanceToSquared(front.center)>points[best].distanceToSquared(front.center)?i:best,front.indices[0])
    : front.indices[0];
  const corner=points[tip].clone().sub(front.center).applyQuaternion(faceOn);
  const upright=new Quaternion().setFromAxisAngle(new Vector3(0,0,1),Math.PI/2-Math.atan2(corner.y,corner.x)+(sides==='6'?Math.PI/4:0));
  // Show the tetrahedron's right face and the cube's top/right faces.
  // Other solids retain the previously reviewed face-forward angle.
  const [pitch,yaw] = ({4:[.12,-.72],6:[.45,-.55]})[sides] ?? [-.12,.08];
  const tilt=new Quaternion().setFromEuler(new Euler(pitch,yaw,0));
  const rotation=tilt.multiply(upright).multiply(faceOn);
  const projected=points.map(p=>p.clone().applyQuaternion(rotation));
  const xs=projected.map(p=>p.x),ys=projected.map(p=>p.y);
  const midX=(Math.max(...xs)+Math.min(...xs))/2,midY=(Math.max(...ys)+Math.min(...ys))/2;
  const scale=42/Math.max(Math.max(...xs)-Math.min(...xs),Math.max(...ys)-Math.min(...ys));
  const xy=p=>[round(24+(p.x-midX)*scale),round(24-(p.y-midY)*scale)];
  const visible=polygons.filter(f=>f.normal.clone().applyQuaternion(rotation).z>1e-5);
  const light=new Vector3(-.45,.65,1).normalize();
  const projectedFaces=visible.map(f=>{
    const n=f.normal.clone().applyQuaternion(rotation);
    return {points:f.indices.map(i=>xy(projected[i]).join(',')).join(' '),shade:round(Math.max(0,(1-n.dot(light))*.25))};
  });
  const label=xy(front.center.clone().applyQuaternion(rotation));
  output[sides]={faces:projectedFaces,label};
  console.log('d'+sides,polygons.length+' faces',visible.length+' visible');
}
