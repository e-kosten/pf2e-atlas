//! User-facing names for the executable catalog. Applicability and collection
//! scope stay in their own descriptor fields rather than being encoded in names.
pub(super) fn field_label(path: &str, scope: Option<&str>) -> Result<&'static str, String> {
    if let Some(label) = super::catalog::embedded_label(path) {
        return Ok(label);
    }
    let label = match (scope, path) {
        (Some("movement.speeds"), "type") => "Movement Type",
        (Some("movement.speeds"), "feet") => "Speed",
        (Some("senses"), "type") => "Sense",
        (Some("defenses.immunities"), "type") => "Immunity",
        (Some("defenses.weaknesses"), "type") => "Weakness",
        (Some("defenses.weaknesses"), "value") => "Weakness Amount",
        (Some("defenses.resistances"), "type") => "Resistance",
        (Some("defenses.resistances"), "value") => "Resistance Amount",
        (Some("spell.damage"), "type") => "Damage Type",
        (Some("spell.damage"), "kinds") => "Damage or Healing",
        (_, "source.pack.id") => "Source Pack ID",
        (_, "source.pack.label") => "Source Pack",
        (_, "source.document_kind") => "Source Document Category",
        (_, "source.type") => "Source Family",
        (_, "kind") => "Kind",
        (_, "traits") => "Traits",
        (_, "rarity") => "Rarity",
        (_, "publication.title") => "Publication",
        (_, "publication.remaster") => "Remastered Publication",
        (_, "level_or_rank") => "Level / Rank",
        (_, "level") => "Level",
        (_, "body.size" | "physical.size" | "ancestry.default_size") => "Size",
        (_, "defenses.ac") => "Armor Class",
        (_, "defenses.hp.maximum" | "shield.hp.maximum") => "Maximum HP",
        (_, "defenses.saves.fortitude") => "Fortitude Save",
        (_, "defenses.saves.reflex") => "Reflex Save",
        (_, "defenses.saves.will") => "Will Save",
        (_, "perception") => "Perception",
        (_, "movement.land") => "Land Speed",
        (_, "hazard.hardness" | "shield.hardness") => "Hardness",
        (_, "hazard.complexity") => "Complex Hazard",
        (_, "languages") => "Languages",
        (_, "movement.speeds") => "Movement Speeds",
        (_, "senses") => "Senses",
        (_, "defenses.immunities") => "Immunities",
        (_, "defenses.weaknesses") => "Weaknesses",
        (_, "defenses.resistances") => "Resistances",
        (_, "spell.rank") => "Spell Rank",
        (_, "spell.focus") => "Focus Spell",
        (_, "spell.ritual") => "Ritual",
        (_, "spell.cantrip") => "Cantrip",
        (_, "spell.casting_time") => "Casting Time",
        (_, "spell.casting_form") => "Casting Actions",
        (_, "spell.defense.save") => "Saving Throw",
        (_, "spell.defense.basic") => "Basic Save",
        (_, "spell.defense.passive") => "Passive Defense",
        (_, "spell.area.type") => "Area Shape",
        (_, "spell.area.size") => "Area Size",
        (_, "spell.sustained") => "Sustained",
        (_, "spell.duration_text") => "Duration",
        (_, "spell.traditions") => "Spell Traditions",
        (_, "spell.damage") => "Spell Damage",
        (_, "physical.unit_price_gp") => "Unit Price (gp)",
        (_, "physical.bulk") => "Bulk",
        (_, "physical.usage") => "Equipment Usage",
        (_, "consumable.damage.kind") => "Consumable Damage or Healing",
        (_, "consumable.damage.type") => "Consumable Damage / Healing Type",
        (_, "consumable.category") => "Consumable Category",
        (_, "weapon.category") => "Weapon Category",
        (_, "weapon.group") => "Weapon Group",
        (_, "weapon.damage.type") => "Weapon Damage Type",
        (_, "weapon.range.increment") => "Range Increment",
        (_, "weapon.reload") => "Reload",
        (_, "armor.category") => "Armor Category",
        (_, "armor.ac_bonus") => "Armor AC Bonus",
        (_, "armor.dex_cap") => "Dexterity Cap",
        (_, "action.type") => "Action Type",
        (_, "action.count") => "Action Count",
        (_, "action.category") => "Action Category",
        (_, "feat.category") => "Feat Category",
        (_, "campaign_feature.category") => "Campaign Feature Category",
        (_, "heritage.ancestry.slug") => "Ancestry",
        (_, "heritage.ancestry.uuid") => "Ancestry Reference",
        (_, "heritage.versatile") => "Versatile Heritage",
        (_, "effect.duration.unit") => "Duration Unit",
        (_, "effect.duration.rounds") => "Duration in Rounds",
        (_, "effect.duration.minutes") => "Duration in Minutes",
        (_, "effect.duration.hours") => "Duration in Hours",
        (_, "effect.duration.days") => "Duration in Days",
        (_, "condition.is_valued") => "Valued Condition",
        (_, "deity.domains.primary") => "Primary Domains",
        (_, "deity.domains.alternate") => "Alternate Domains",
        (_, "deity.fonts") => "Divine Fonts",
        _ => {
            return Err(format!(
                "catalog field {scope:?}/{path} needs a user-facing label"
            ));
        }
    };
    Ok(label)
}
